import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
test('independent mock server serves UI, errors and disconnect/recovery without Jetson',async t=>{
 const child=spawn(process.execPath,['server.mjs','--mock'],{cwd:fileURLToPath(new URL('..',import.meta.url)),env:{...process.env,PORT:'0'},stdio:['ignore','pipe','pipe']});
 t.after(()=>child.kill());
 const base=await new Promise((resolve,reject)=>{
   const timer=setTimeout(()=>reject(new Error('server startup timeout')),5000);
   child.once('error',reject);child.stdout.on('data',chunk=>{const match=chunk.toString().match(/http:\/\/127\.0\.0\.1:\d+/);if(match){clearTimeout(timer);resolve(match[0]);}});
 });
 const get=path=>fetch(base+path,{signal:AbortSignal.timeout(3000)});
 const index=await get('/');assert.equal(index.status,200);
 const html=await index.text();
 assert.equal(html,await readFile(new URL('../public/index.html',import.meta.url),'utf8'));
 assert.match(html,/<button[^>]*id="settingsToggle"/);
 assert.match(html,/<dialog id="settingsDialog"/);
 assert.equal((await get('/settings?embedded=1')).status,200);
 assert.match(html,/<dialog id="helpDialog"/);
 assert.match(html, /id="modeToggle"/);
 assert.doesNotMatch(html, /id="timelinePanel"/);
 assert.match(html, /id="assemblyZoneCard"/);
 assert.match(html, /id="completedZoneCard"/);
 assert.match(html, /src="data:image\/webp;base64,/);
 assert.match(html, /id="healthFps"/);
 const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
 assert.equal(new Set(ids).size,ids.length,'unique element identifiers');
 assert.doesNotMatch(html,/<dialog[^>]* open/);
 assert.match(html,/前端联调/);
 assert.equal((await get('/%2e%2e%2fserver.mjs')).status,404);
 assert.equal((await get('/api/v1/camera')).status,200);
 const beforeLanguage=await (await get('/api/v1/settings')).json();
 for(const language of ['zh-CN','en'])assert.equal((await get('/api/frame.jpg?lang='+language)).headers.get('content-language'),language);
 assert.equal((await get('/api/frame.jpg?lang=invalid')).status,400);
 assert.equal((await get('/api/frame.jpg?lang=')).status,400);
 assert.equal((await (await get('/api/v1/settings')).json()).revision,beforeLanguage.revision);
 const action=action=>fetch(base+'/api/v1/work/actions',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({action}),signal:AbortSignal.timeout(3000)});
 assert.equal((await action('invalid')).status,400);assert.equal((await action('start')).status,409);
 await get('/mock/scenario?name=offline');assert.equal((await get('/api/v1/video.jpg')).status,503);assert.equal((await (await get('/api/v1/observations/latest')).json()).fresh,false);
 await get('/mock/scenario?name=working');const image=await get('/api/v1/video.jpg');assert.equal(image.status,200);assert.equal((await get('/api/frame.jpg')).status,200);assert.equal(image.headers.get('content-type'),'image/jpeg');assert.equal((await (await get('/api/v1/observations/latest')).json()).fresh,true);
 assert.equal((await action('end')).status,200);assert.equal((await (await get('/api/v1/work/status')).json()).active,false);
});
